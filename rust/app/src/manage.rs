/// The third-party licence notices, generated by `tools/third_party_notices.py` and shown on the
/// About page. Embedded here, so the executable carries them.
const THIRD_PARTY_NOTICES: &str = include_str!("../../../THIRD-PARTY-NOTICES.txt");

/// What the settings need from the app that the engine does not give them.
pub(crate) struct Persist {
    /// The settings file. `None` in demo mode: nothing is written there.
    pub(crate) path: Option<PathBuf>,
    /// Rewrites the `.rdp` files after a change. `None` in demo mode.
    pub(crate) rdp: Option<Arc<RdpLauncher>>,
    /// The TCP probe of the wizard's checks.
    pub(crate) ports: Arc<dyn PortProbe>,
    /// Runs `ssh` for the checks.
    pub(crate) runner: Arc<dyn CommandRunner>,
    /// Opens the links of the About page. A real runner in every mode: a demo never starts it
    /// for a check, but the link still opens.
    pub(crate) opener: Arc<dyn CommandRunner>,
}

/// What [`install`] needs.
pub(crate) struct Setup {
    /// The configuration the engine runs with.
    pub(crate) config: Config,
    /// The texts, in the language of the settings.
    pub(crate) translator: Translator,
    /// Sends the new configuration to the engine.
    pub(crate) handle: Handle,
    /// The application theme.
    pub(crate) dark: bool,
    /// The file and the adapters of the changes.
    pub(crate) persist: Persist,
}

/// A delete that waits for its second click.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Armed {
    /// The delete button of this tunnel.
    Tunnel(String),
    /// The delete button of this PC.
    Pc(String),
}

/// What a click on a "Видалити" button does.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum DeleteStep {
    /// The first click: this delete now waits for its confirmation.
    Arm(Armed),
    /// The second click on the same button: delete.
    Delete,
}

/// The two-click delete: a click on the button that is armed deletes; a click on any other
/// button arms that one instead (replacing the armed one).
pub(crate) fn delete_step(armed: Option<&Armed>, clicked: Armed) -> DeleteStep {
    if armed == Some(&clicked) {
        DeleteStep::Delete
    } else {
        DeleteStep::Arm(clicked)
    }
}

/// The settings, the tunnel form and the wizard, and the state behind them. Lives on the event
/// loop thread (see [`with_manage`]).
pub(crate) struct Manage {
    pub(crate) tr: Translator,
    pub(crate) handle: Handle,
    pub(crate) persist: Persist,
    /// The configuration on screen: the one the engine runs with.
    pub(crate) config: RefCell<Config>,
    armed: RefCell<Option<Armed>>,
    /// The tunnel being added or edited, while its form is open.
    form: RefCell<Option<TunnelForm>>,
    /// The wizard's session, while it is open.
    pub(crate) session: RefCell<Option<wizard_ui::Session>>,
    /// Counts the runs of the checks; a result of an older run is dropped.
    pub(crate) check_run: Cell<u64>,
    /// Counts the opening of the wizard; the result of a key made for an earlier one is dropped.
    pub(crate) session_id: Cell<u64>,
    /// Counts the offers of a host key; an answer for an older one is dropped.
    pub(crate) trust_run: Cell<u64>,
    pub(crate) settings: SettingsWindow,
    pub(crate) form_window: TunnelFormWindow,
    pub(crate) wizard: WizardWindow,
}

thread_local! {
    /// The state of the settings on this thread. Set once by [`install`].
    static MANAGE: RefCell<Option<Rc<Manage>>> = const { RefCell::new(None) };
}

/// Runs `f` with the settings state. Does nothing before [`install`].
pub(crate) fn with_manage(f: impl FnOnce(&Manage)) {
    let manage = MANAGE.with(|slot| slot.borrow().clone());
    if let Some(manage) = manage {
        f(&manage);
    }
}

/// Creates the settings windows, fills their texts, wires their callbacks and makes the
/// "Налаштування" button of the panel open the settings. Call on the event loop thread.
pub(crate) fn install(panel: &Panel, setup: Setup) -> Result<(), slint::PlatformError> {
    let settings = SettingsWindow::new()?;
    let form_window = TunnelFormWindow::new()?;
    let wizard = WizardWindow::new()?;
    let about = About::new(
        env!("CARGO_PKG_VERSION"),
        Some(include_str!("../../Cargo.lock")),
    );
    let tr = &setup.translator;

    settings.global::<Theme>().set_dark(setup.dark);
    form_window.global::<Theme>().set_dark(setup.dark);
    wizard.global::<Theme>().set_dark(setup.dark);
    fill_words(&settings.global::<Words>(), tr);
    fill_words(&form_window.global::<Words>(), tr);
    fill_words(&wizard.global::<Words>(), tr);

    settings.set_version_text(
        tr.t("about.version", &[("version", about.version.as_str())])
            .into(),
    );
    settings.set_slint_version(
        about
            .slint_version
            .as_deref()
            .map(|version| tr.t("about.slint_version", &[("version", version)]))
            .unwrap_or_default()
            .into(),
    );
    settings.set_slint_url(about.slint_url.into());
    settings.set_notices(THIRD_PARTY_NOTICES.into());
    settings.set_glyph(icon::to_image(&icon::render(
        DisplayState::Unknown,
        Attention::None,
        setup.dark,
        48,
    )));

    wire_settings(&settings);
    form_window
        .global::<Flow>()
        .on_advance(|| with_manage(Manage::save_form));
    form_window.on_cancel(|| with_manage(Manage::cancel_form));
    wire_wizard(&wizard);
    on_escape(settings.window(), escape_settings);
    on_escape(form_window.window(), escape_form);
    on_escape(wizard.window(), escape_wizard);
    form_window.window().on_close_requested(|| {
        with_manage(Manage::forget_form);
        CloseRequestResponse::HideWindow
    });
    wizard.window().on_close_requested(|| {
        with_manage(Manage::forget_session);
        CloseRequestResponse::HideWindow
    });
    panel
        .global::<Nav>()
        .on_settings_clicked(|| with_manage(Manage::open_settings));

    let manage = Rc::new(Manage {
        tr: setup.translator,
        handle: setup.handle,
        persist: setup.persist,
        config: RefCell::new(setup.config),
        armed: RefCell::new(None),
        form: RefCell::new(None),
        session: RefCell::new(None),
        check_run: Cell::new(0),
        session_id: Cell::new(0),
        trust_run: Cell::new(0),
        settings,
        form_window,
        wizard,
    });
    MANAGE.with(|slot| *slot.borrow_mut() = Some(manage));
    Ok(())
}

fn wire_settings(settings: &SettingsWindow) {
    settings.on_add_tunnel(|| with_manage(|m| m.open_form(None)));
    settings.on_add_pc(|| with_manage(|m| m.open_wizard_new()));
    settings.on_edit_tunnel(|id| with_manage(|m| m.open_form(Some(id.as_str()))));
    settings.on_edit_pc(|id| with_manage(|m| m.open_wizard_edit(id.as_str())));
    settings.on_delete_tunnel(|id| with_manage(|m| m.delete_tunnel(id.as_str())));
    settings.on_delete_pc(|id| with_manage(|m| m.delete_pc(id.as_str())));
    settings.on_disarm(|| with_manage(Manage::disarm));
    settings.on_open_link(|url| {
        with_manage(|m| links::open(Arc::clone(&m.persist.opener), url.to_string()));
    });
}

fn wire_wizard(wizard: &WizardWindow) {
    wizard
        .global::<Flow>()
        .on_advance(|| with_manage(Manage::wizard_advance));
    wizard.on_back(|| with_manage(Manage::wizard_back));
    wizard.on_cancel(|| with_manage(Manage::cancel_wizard));
    wizard.on_retest(|| with_manage(Manage::wizard_retest));
    wizard.on_create_key(|which| with_manage(|m| m.create_key(which)));
    wizard.on_refresh_help(|| with_manage(Manage::refresh_help));
    wizard.on_trust_host(|index| with_manage(|m| m.trust_host(index)));
    wizard.on_trust_confirm(|| with_manage(Manage::trust_confirm));
    wizard.on_trust_cancel(|| with_manage(Manage::trust_cancel));
}

/// Esc closes the window (or, in the settings, cancels a waiting delete first). The action runs
/// once the window has finished the event that carried the key.
fn on_escape(window: &slint::Window, action: fn()) {
    window.on_winit_window_event(move |_, event| {
        if let WindowEvent::KeyboardInput { event: key, .. } = event
            && key.state == ElementState::Pressed
            && key.logical_key == Key::Named(NamedKey::Escape)
        {
            let _ = slint::invoke_from_event_loop(action);
        }
        EventResult::Propagate
    });
}

fn escape_settings() {
    with_manage(Manage::escape_settings);
}

fn escape_form() {
    with_manage(Manage::cancel_form);
}

fn escape_wizard() {
    with_manage(Manage::cancel_wizard);
}

