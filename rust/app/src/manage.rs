/// A model of `items`.
pub(crate) fn model<T: Clone + 'static>(items: Vec<T>) -> ModelRc<T> {
    ModelRc::new(VecModel::from(items))
}

/// Puts each problem under its field: `slot` gives the index of a field in the window's array
/// of `count` errors (the first problem of a field wins). A problem of no field of the window
/// is returned as a text of its own, together with the rest.
pub(crate) fn place_problems(
    tr: &Translator,
    problems: &[Problem],
    slot: fn(&str) -> Option<usize>,
    count: usize,
) -> (Vec<SharedString>, String) {
    let mut fields = vec![SharedString::default(); count];
    let mut general = Vec::new();
    for problem in problems {
        let text = tr.problem(problem);
        match slot(problem.field).and_then(|index| fields.get_mut(index)) {
            Some(cell) if cell.is_empty() => *cell = text.into(),
            Some(_) => {}
            None => general.push(text),
        }
    }
    (fields, general.join("\n"))
}

/// The index of a tunnel form field in its errors.
fn tunnel_slot(field: &str) -> Option<usize> {
    match field {
        tunnel_form::field::NAME => Some(0),
        tunnel_form::field::CONF => Some(1),
        tunnel_form::field::PROBE_HOST => Some(2),
        _ => None,
    }
}

impl Manage {
    /// Writes a change (unless demo), reloads the engine with it, refreshes the `.rdp` files
    /// and keeps it as the configuration on screen. On a failed write nothing changes, and the
    /// text says why.
    pub(crate) fn commit(&self, change: Change) -> Result<(), String> {
        if let Some(path) = &self.persist.path {
            change.save(path).map_err(|err| {
                self.tr
                    .t("wizard.save_failed", &[("detail", &err.to_string())])
            })?;
        }
        self.handle.reload(change.config.clone());
        if let Some(rdp) = &self.persist.rdp {
            rdp.update(&change.config);
        }
        *self.config.borrow_mut() = change.config;
        Ok(())
    }

    /// The blink phase of the busy markers, shown as the panel shows it.
    pub(crate) fn set_blink(&self, on: bool) {
        self.settings.global::<Motion>().set_blink_on(on);
        self.wizard.global::<Motion>().set_blink_on(on);
    }

    /// Shows the settings window in front of the others, and its lists as they are now.
    fn open_settings(&self) {
        // Anything that happened before the window was closed is forgotten, a waiting delete too.
        *self.armed.borrow_mut() = None;
        self.settings.set_page_error("".into());
        self.refresh();
        show_in_front(&self.settings);
    }

    /// Esc on the settings: cancels a waiting delete, else closes the window.
    fn escape_settings(&self) {
        if self.armed.borrow().is_some() {
            self.disarm();
        } else {
            let _ = self.settings.hide();
        }
    }

    /// Fills the lists of the settings from the configuration on screen.
    pub(crate) fn refresh(&self) {
        let armed = self.armed.borrow().clone();
        let (tunnels, pcs, hint) = {
            let config = self.config.borrow();
            let tunnels: Vec<SettingsRow> = settings::tunnel_rows(&config)
                .iter()
                .map(|row| self.settings_row(row, armed == Some(Armed::Tunnel(row.id.clone()))))
                .collect();
            let pcs: Vec<SettingsRow> = settings::pc_rows(&config)
                .iter()
                .map(|row| self.settings_row(row, armed == Some(Armed::Pc(row.id.clone()))))
                .collect();
            let hint = match &armed {
                Some(Armed::Tunnel(id)) => config
                    .tunnels
                    .iter()
                    .find(|t| t.id.to_string() == *id)
                    .map(|t| {
                        self.tr
                            .t("confirm.delete_tunnel", &[("tunnel", t.name.as_str())])
                    }),
                Some(Armed::Pc(id)) => config
                    .pcs
                    .iter()
                    .find(|p| p.id.to_string() == *id)
                    .map(|p| self.tr.t("confirm.delete", &[("pc", p.name.as_str())])),
                None => None,
            };
            (tunnels, pcs, hint.unwrap_or_default())
        };
        self.settings.set_tunnels(model(tunnels));
        self.settings.set_pcs(model(pcs));
        self.settings.set_armed_hint(hint.into());
    }

    fn settings_row(&self, row: &settings::Row, armed: bool) -> SettingsRow {
        SettingsRow {
            id: row.id.clone().into(),
            name: row.name.clone().into(),
            secondary: self.tr.secondary(&row.secondary).into(),
            armed,
        }
    }

    /// Makes `armed` the waiting delete (replacing any other), or none.
    fn set_armed(&self, armed: Option<Armed>) {
        *self.armed.borrow_mut() = armed;
        self.settings.set_page_error("".into());
        self.refresh();
    }

    fn disarm(&self) {
        if self.armed.borrow().is_some() {
            self.set_armed(None);
        }
    }

    /// The first click on "Видалити" arms it; the second deletes; any other click cancels.
    fn delete_tunnel(&self, id: &str) {
        let Ok(tunnel) = TunnelId::parse(id) else {
            return;
        };
        let step = delete_step(self.armed.borrow().as_ref(), Armed::Tunnel(id.to_owned()));
        if let DeleteStep::Arm(armed) = step {
            self.set_armed(Some(armed));
            return;
        }
        self.set_armed(None);
        let result = settings::delete_tunnel(&self.config.borrow(), &tunnel);
        match result {
            Ok(change) => self.apply_list_change(change),
            Err(problems) => self.show_page_error(&problems),
        }
    }

    /// As [`Manage::delete_tunnel`], for a PC.
    fn delete_pc(&self, id: &str) {
        let Ok(pc) = PcId::parse(id) else {
            return;
        };
        let step = delete_step(self.armed.borrow().as_ref(), Armed::Pc(id.to_owned()));
        if let DeleteStep::Arm(armed) = step {
            self.set_armed(Some(armed));
            return;
        }
        self.set_armed(None);
        let change = settings::delete_pc(&self.config.borrow(), &pc);
        match change {
            Some(change) => self.apply_list_change(change),
            None => self.refresh(),
        }
    }

    fn apply_list_change(&self, change: Change) {
        match self.commit(change) {
            Ok(()) => self.refresh(),
            Err(text) => self.settings.set_page_error(text.into()),
        }
    }

    fn show_page_error(&self, problems: &[Problem]) {
        let text = problems
            .iter()
            .map(|problem| self.tr.problem(problem))
            .collect::<Vec<_>>()
            .join("\n");
        self.settings.set_page_error(text.into());
    }

    /// Opens the tunnel form for a new tunnel, or for the tunnel `id`.
    fn open_form(&self, id: Option<&str>) {
        self.disarm_quietly();
        let (form, heading) = {
            let config = self.config.borrow();
            match id
                .and_then(|id| TunnelId::parse(id).ok())
                .and_then(|id| config.tunnel(&id))
            {
                Some(tunnel) => (
                    TunnelForm::from_tunnel(tunnel),
                    self.tr.t(
                        "tunnel.form.title_edit",
                        &[("tunnel", tunnel.name.as_str())],
                    ),
                ),
                None => (
                    TunnelForm::new(&config),
                    self.tr.t("tunnel.form.title_add", &[]),
                ),
            }
        };
        let window = &self.form_window;
        window.set_heading(heading.into());
        window.set_name(form.name.clone().into());
        window.set_conf(form.conf.clone().into());
        window.set_probe_host(form.probe_host.clone().into());
        window.set_errors(model(vec![SharedString::default(); 3]));
        window.set_general_error("".into());
        *self.form.borrow_mut() = Some(form);
        show_in_front(window);
    }

    /// Clears a waiting delete without redrawing (the caller redraws).
    fn disarm_quietly(&self) {
        *self.armed.borrow_mut() = None;
    }

    /// "Зберегти" of the tunnel form: saves the typed values, or shows what is wrong.
    fn save_form(&self) {
        let Some(mut form) = self.form.borrow().clone() else {
            return;
        };
        form.name = self.form_window.get_name().to_string();
        form.conf = self.form_window.get_conf().to_string();
        form.probe_host = self.form_window.get_probe_host().to_string();
        let result = settings::save_tunnel(&self.config.borrow(), &form);
        match result {
            Err(problems) => {
                let (errors, general) = place_problems(&self.tr, &problems, tunnel_slot, 3);
                self.form_window.set_errors(model(errors));
                self.form_window.set_general_error(general.into());
            }
            Ok(change) => match self.commit(change) {
                Ok(()) => {
                    self.close_form();
                    self.refresh();
                }
                Err(text) => self.form_window.set_general_error(text.into()),
            },
        }
    }

    fn cancel_form(&self) {
        self.close_form();
    }

    fn close_form(&self) {
        self.forget_form();
        let _ = self.form_window.hide();
    }

    /// The form is gone (closed by its frame): the draft is dropped.
    fn forget_form(&self) {
        *self.form.borrow_mut() = None;
    }

    /// The session of the wizard is gone (closed by its frame).
    fn forget_session(&self) {
        *self.session.borrow_mut() = None;
    }
}

/// Shows `window`, and brings it to the front if it was minimised or behind other windows.
pub(crate) fn show_in_front<C: ComponentHandle>(window: &C) {
    let _ = window.show();
    let _ = window.window().with_winit_window(|w| {
        w.set_minimized(false);
        w.focus_window();
    });
}

